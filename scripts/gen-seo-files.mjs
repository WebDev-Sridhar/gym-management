/**
 * gen-seo-files.mjs — emit dist/robots.txt and dist/sitemap.xml at build time.
 *
 * Runs after `vite build`, before/independent of prerender. Idempotent:
 * deterministic output from MARKETING_ROUTES + SITE.URL, no runtime cost.
 *
 * robots.txt blocks the authenticated app surfaces and points crawlers at the
 * sitemap. sitemap.xml lists only public, indexable marketing URLs.
 */
import { writeFileSync, copyFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { SITE } from '../src/lib/constants/routes.js'
import { MARKETING_ROUTES } from './marketing-routes.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const DIST = resolve(__dirname, '../dist')
const BASE = SITE.URL.replace(/\/$/, '')
const today = new Date().toISOString().slice(0, 10)

// ── Shell decoupling (CRITICAL) ──────────────────────────────────────────────
// middleware.js fetches /__shell.html (NOT /index.html) to inject per-gym OG
// tags. We snapshot the pristine Vite shell here, BEFORE prerender overwrites
// dist/index.html with the rendered marketing homepage. Done in this script
// (pure fs, always succeeds) so tenant OG injection never breaks even if the
// best-effort prerender step is skipped on a CI runner without Chromium.
const indexHtml = resolve(DIST, 'index.html')
if (existsSync(indexHtml)) {
  copyFileSync(indexHtml, resolve(DIST, '__shell.html'))
  console.log('[seo] wrote __shell.html (pristine SPA shell for middleware OG injection)')
} else {
  console.warn('[seo] dist/index.html missing — run `vite build` first')
}

// ── robots.txt ───────────────────────────────────────────────────────────────
const robots = `# Gymmobius robots.txt — generated by scripts/gen-seo-files.mjs
User-agent: *
Allow: /
Disallow: /owner-dashboard
Disallow: /trainer-dashboard
Disallow: /member-app
Disallow: /admin
Disallow: /auth/
Disallow: /login
Disallow: /signup
Disallow: /reset-password
Disallow: /create-gym
Disallow: /onboarding
Disallow: /billing
Disallow: /pay/
Disallow: /checkin

Sitemap: ${BASE}/sitemap.xml
`
writeFileSync(resolve(DIST, 'robots.txt'), robots, 'utf8')

// ── sitemap.xml ──────────────────────────────────────────────────────────────
const urlFor = (path) => `${BASE}${path === '/' ? '/' : path.replace(/\/$/, '')}`

const urls = MARKETING_ROUTES.map(
  ({ path, changefreq, priority }) => `  <url>
    <loc>${urlFor(path)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`,
).join('\n')

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`
writeFileSync(resolve(DIST, 'sitemap.xml'), sitemap, 'utf8')

console.log(`[seo] wrote robots.txt + sitemap.xml (${MARKETING_ROUTES.length} urls) to dist/`)
